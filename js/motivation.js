// Whole days since the epoch, in local time, so the sentence changes at midnight.
export function dailyMotivation(date = new Date()) {
  const dayNumber = Math.floor(Date.UTC(date.getFullYear(), date.getMonth(), date.getDate()) / 86400000);
  return MOTIVATIONS[((dayNumber % MOTIVATIONS.length) + MOTIVATIONS.length) % MOTIVATIONS.length];
}
